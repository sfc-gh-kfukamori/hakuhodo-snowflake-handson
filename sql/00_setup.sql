-- ============================================================================
-- 博報堂 Snowflake ハンズオン
-- Section 0: 環境セットアップ
-- ============================================================================
-- このセクションでは、ハンズオンで使用するデータベース、スキーマ、
-- ウェアハウスなどの基盤オブジェクトを作成します。
-- ============================================================================

-- ============================================================================
-- Step 0-1: ロールの設定
-- ============================================================================
-- SYSADMIN ロールでオブジェクトを作成します。
-- 実運用では専用ロールを作成することを推奨しますが、
-- ハンズオンでは簡略化のため SYSADMIN を使用します。
USE ROLE SYSADMIN;

-- ============================================================================
-- Step 0-2: ウェアハウスの作成
-- ============================================================================
-- Snowflake のウェアハウスはコンピュートリソースです。
-- サイズを変更することで処理能力をスケールできます。
-- AUTO_SUSPEND=60 で1分間アイドル後に自動停止し、コストを抑えます。
CREATE OR REPLACE WAREHOUSE HAKUHODO_HANDSON_WH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = '博報堂ハンズオン用ウェアハウス';

-- ============================================================================
-- Step 0-3: データベースとスキーマの作成
-- ============================================================================
CREATE OR REPLACE DATABASE HAKUHODO_HANDSON_DB
    COMMENT = '博報堂ハンズオン用データベース';

CREATE OR REPLACE SCHEMA HAKUHODO_HANDSON_DB.HAKUHODO_HANDSON_SCHEMA
    COMMENT = '博報堂ハンズオン用スキーマ';

-- 以降の操作で使用するコンテキストを設定
USE DATABASE HAKUHODO_HANDSON_DB;
USE SCHEMA HAKUHODO_HANDSON_SCHEMA;
USE WAREHOUSE HAKUHODO_HANDSON_WH;

-- ============================================================================
-- Step 0-4: Streamlit / Dynamic Table 用の追加スキーマ（後のセクションで使用）
-- ============================================================================
CREATE OR REPLACE SCHEMA HAKUHODO_HANDSON_DB.ANALYTICS
    COMMENT = '加工済みデータ用スキーマ';

CREATE OR REPLACE SCHEMA HAKUHODO_HANDSON_DB.STREAMLIT
    COMMENT = 'Streamlit アプリ用スキーマ';

-- ============================================================================
-- 確認: 作成されたオブジェクトを確認しましょう
-- ============================================================================
SHOW DATABASES LIKE 'HAKUHODO_HANDSON_DB';
SHOW SCHEMAS IN DATABASE HAKUHODO_HANDSON_DB;
SHOW WAREHOUSES LIKE 'HAKUHODO_HANDSON_WH';

