-- このセクションでは以下を学びます:
--   1. CORTEX.COMPLETE: LLMによるテキスト生成・分析
--   2. CORTEX.SUMMARIZE: テキスト要約
--   3. CORTEX.TRANSLATE: 多言語翻訳
--   4. CORTEX.SENTIMENT: 感情分析
--   5. CORTEX.EXTRACT_ANSWER: 質問応答（テキストから回答抽出）
--
-- ★ Snowflake Cortex AI Function とは:
--   SQL文の中でLLM（大規模言語モデル）を直接呼び出せる機能です。
--   データをSnowflake外に出すことなく、AI処理をSQLで実行できます。
--   ETLパイプラインやレポート生成に組み込むことで、
--   データ分析の自動化・高度化が可能になります。
