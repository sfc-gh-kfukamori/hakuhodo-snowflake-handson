USE ROLE SYSADMIN;
USE DATABASE HAKUHODO_HANDSON_DB;
USE SCHEMA ANALYTICS;
USE WAREHOUSE HAKUHODO_HANDSON_WH;

-- ============================================================================
-- 1. CORTEX.COMPLETE — LLMによるテキスト生成・データ分析
-- ============================================================================
-- COMPLETE はプロンプトを与えて自由なテキスト生成を行う関数です。
-- データの要約、コメント生成、分析レポートの自動作成に活用できます。

-- --------------------------------------------------------------------------
-- 例1-1: 仕入データのサマリコメントを自動生成
-- --------------------------------------------------------------------------
-- 月次集計データから、各月の特徴を AI に分析させます。

SELECT
    "年月",
    "会社_営業_名_最新",
    "仕入高合計",
    "媒体収益合計",
    "媒体収益予算合計",
    SNOWFLAKE.CORTEX.COMPLETE(
        'claude-4-sonnet',
        '以下の月次仕入データについて、50文字以内で簡潔な分析コメントを日本語で生成してください。' ||
        '年月: ' || "年月"::VARCHAR ||
        ', 会社: ' || COALESCE("会社_営業_名_最新", 'N/A') ||
        ', 仕入高: ' || COALESCE("仕入高合計"::VARCHAR, '0') || '円' ||
        ', 媒体収益実績: ' || COALESCE("媒体収益合計"::VARCHAR, '0') || '円' ||
        ', 媒体収益予算: ' || COALESCE("媒体収益予算合計"::VARCHAR, '0') || '円'
    ) AS "AI分析コメント"
FROM DT_PURCHASE_MONTHLY_SUMMARY
WHERE "仕入高合計" IS NOT NULL AND "仕入高合計" > 0
ORDER BY "年月" DESC, "仕入高合計" DESC
LIMIT 5;

-- --------------------------------------------------------------------------
-- 例1-2: 組織損益データの総合分析レポート生成
-- --------------------------------------------------------------------------
-- 部門別の予実データを集約し、全体のレポートを AI で生成します。

WITH dept_summary AS (
    SELECT
        "部門",
        SUM("実績合計") AS "実績計",
        SUM("予算合計") AS "予算計",
        CASE WHEN SUM("予算合計") = 0 THEN NULL
             ELSE ROUND(SUM("実績合計") * 100.0 / SUM("予算合計"), 1)
        END AS "達成率"
    FROM DT_SPECIAL_FEE_SUMMARY
    GROUP BY "部門"
    HAVING SUM("予算合計") <> 0
    ORDER BY "達成率" DESC
    LIMIT 10
)
SELECT SNOWFLAKE.CORTEX.COMPLETE(
    'claude-4-sonnet',
    '以下は部門別の予算達成状況です。全体の傾向と注目すべきポイントを200文字以内で日本語で分析してください。\n\n' ||
    LISTAGG(
        '部門: ' || COALESCE("部門", 'N/A') ||
        ' | 実績: ' || "実績計"::VARCHAR ||
        '円 | 予算: ' || "予算計"::VARCHAR ||
        '円 | 達成率: ' || COALESCE("達成率"::VARCHAR, 'N/A') || '%',
        '\n'
    ) WITHIN GROUP (ORDER BY "達成率" DESC)
) AS "AI総合分析レポート"
FROM dept_summary;

-- --------------------------------------------------------------------------
-- 例1-3: 広告主業種のトレンド分析
-- --------------------------------------------------------------------------

WITH industry_data AS (
    SELECT
        "広告主業種_大名",
        SUM("仕入高合計") AS "仕入高計",
        SUM("取引件数") AS "取引件数計"
    FROM DT_PURCHASE_MONTHLY_SUMMARY
    WHERE "広告主業種_大名" IS NOT NULL
    GROUP BY "広告主業種_大名"
    ORDER BY "仕入高計" DESC
    LIMIT 10
)
SELECT SNOWFLAKE.CORTEX.COMPLETE(
    'claude-4-sonnet',
    '以下は広告主業種別の仕入高データです。どの業種が大きく、今後の営業戦略への示唆を100文字以内で日本語で述べてください。\n\n' ||
    LISTAGG(
        '業種: ' || "広告主業種_大名" ||
        ' | 仕入高: ' || "仕入高計"::VARCHAR || '円' ||
        ' | 取引件数: ' || "取引件数計"::VARCHAR,
        '\n'
    ) WITHIN GROUP (ORDER BY "仕入高計" DESC)
) AS "業種トレンド分析"
FROM industry_data;

-- ============================================================================
-- 2. CORTEX.SUMMARIZE — テキスト要約
-- ============================================================================
-- SUMMARIZE は長いテキストを要約する関数です。
-- レポートや議事録の要約に活用できます。

-- --------------------------------------------------------------------------
-- 例2-1: 複数部門の損益状況を要約
-- --------------------------------------------------------------------------

WITH report_text AS (
    SELECT LISTAGG(
        "部門" || 'の' || "管理項目名称" || ': 実績' ||
        "実績合計"::VARCHAR || '円、予算' || "予算合計"::VARCHAR || '円、' ||
        '達成率' || COALESCE("予実達成率"::VARCHAR, 'N/A') || '%。',
        ' '
    ) WITHIN GROUP (ORDER BY "部門", "管理項目名称") AS full_report
    FROM DT_SPECIAL_FEE_SUMMARY
    WHERE "予算合計" <> 0
    LIMIT 50
)
SELECT SNOWFLAKE.CORTEX.SUMMARIZE(full_report) AS "要約レポート"
FROM report_text;

-- ============================================================================
-- 3. CORTEX.TRANSLATE — 多言語翻訳
-- ============================================================================
-- TRANSLATE は指定した言語間でテキストを翻訳する関数です。
-- グローバル展開時のレポート翻訳に活用できます。

-- --------------------------------------------------------------------------
-- 例3-1: 日本語の分析結果を英語に翻訳
-- --------------------------------------------------------------------------

SELECT
    "部門" AS "部門名",
    "管理項目名称",
    "実績合計",
    "予算合計",
    SNOWFLAKE.CORTEX.TRANSLATE(
        "部門" || 'の' || "管理項目名称" || 'について、実績は' ||
        "実績合計"::VARCHAR || '円で、予算' || "予算合計"::VARCHAR || '円に対して' ||
        COALESCE("予実達成率"::VARCHAR, 'N/A') || '%の達成率です。',
        'ja',
        'en'
    ) AS "English Translation"
FROM DT_SPECIAL_FEE_SUMMARY
WHERE "予算合計" <> 0
ORDER BY "実績合計" DESC
LIMIT 5;

-- --------------------------------------------------------------------------
-- 例3-2: 英語・中国語・韓国語への多言語翻訳
-- --------------------------------------------------------------------------

WITH source_text AS (
    SELECT '博報堂グループの媒体収益は前年同期比で堅調に推移しています。' AS text_ja
)
SELECT
    text_ja AS "日本語",
    SNOWFLAKE.CORTEX.TRANSLATE(text_ja, 'ja', 'en') AS "English",
    SNOWFLAKE.CORTEX.TRANSLATE(text_ja, 'ja', 'zh') AS "中文",
    SNOWFLAKE.CORTEX.TRANSLATE(text_ja, 'ja', 'ko') AS "한국어"
FROM source_text;

-- ============================================================================
-- 4. CORTEX.SENTIMENT — 感情分析
-- ============================================================================
-- SENTIMENT はテキストの感情スコアを -1（ネガティブ）〜 +1（ポジティブ）で返します。
-- 顧客フィードバックや市場コメントの分析に活用できます。

-- --------------------------------------------------------------------------
-- 例4-1: 予実状況に対するコメントの感情分析
-- --------------------------------------------------------------------------
-- ビジネスコンテキストのテキストに対して感情分析を実施します。

SELECT
    comment_text AS "コメント",
    SNOWFLAKE.CORTEX.SENTIMENT(comment_text) AS "感情スコア",
    CASE
        WHEN SNOWFLAKE.CORTEX.SENTIMENT(comment_text) > 0.3 THEN 'ポジティブ'
        WHEN SNOWFLAKE.CORTEX.SENTIMENT(comment_text) < -0.3 THEN 'ネガティブ'
        ELSE 'ニュートラル'
    END AS "感情判定"
FROM (
    SELECT '今期の売上は目標を大幅に上回り、過去最高を記録しました。' AS comment_text
    UNION ALL
    SELECT '広告市場の低迷により、仕入高が前年を下回る厳しい状況が続いています。'
    UNION ALL
    SELECT '第2四半期の実績は予算並みで推移しています。'
    UNION ALL
    SELECT 'デジタル広告の成長が著しく、新規顧客の獲得も順調です。'
    UNION ALL
    SELECT 'コスト増加が利益を圧迫し、収益改善が急務となっています。'
);

-- --------------------------------------------------------------------------
-- 例4-2: AI生成コメントの感情分析（COMPLETE + SENTIMENT の組み合わせ）
-- --------------------------------------------------------------------------

WITH ai_comments AS (
    SELECT
        "部門",
        "予実達成率",
        SNOWFLAKE.CORTEX.COMPLETE(
            'claude-4-sonnet',
            '予算達成率が' || COALESCE("予実達成率"::VARCHAR, '0') ||
            '%の部門について、30文字以内で状況を述べてください。日本語で。'
        ) AS ai_comment
    FROM DT_SPECIAL_FEE_SUMMARY
    WHERE "予算合計" <> 0
    ORDER BY "予実達成率" DESC
    LIMIT 5
)
SELECT
    "部門",
    "予実達成率",
    ai_comment AS "AIコメント",
    ROUND(SNOWFLAKE.CORTEX.SENTIMENT(ai_comment), 3) AS "感情スコア"
FROM ai_comments;

-- ============================================================================
-- 5. CORTEX.EXTRACT_ANSWER — 質問応答
-- ============================================================================
-- EXTRACT_ANSWER はテキストの中から特定の質問に対する回答を抽出する関数です。
-- レポートやドキュメントからの情報抽出に活用できます。

-- --------------------------------------------------------------------------
-- 例5-1: レポートテキストからの情報抽出
-- --------------------------------------------------------------------------

SELECT SNOWFLAKE.CORTEX.EXTRACT_ANSWER(
    '2025年度第1四半期の博報堂グループ全体の媒体仕入高は約500億円で、' ||
    '前年同期比105%となりました。特にデジタル広告分野が前年比120%と大きく成長し、' ||
    'テレビ広告は98%とやや減少しました。営業利益は45億円で、' ||
    'スタッフコストの増加を媒体収益の伸びでカバーしています。',
    'デジタル広告の前年比は何%ですか？'
) AS "回答";

-- --------------------------------------------------------------------------
-- 例5-2: 複数の質問を一度に処理
-- --------------------------------------------------------------------------

WITH report AS (
    SELECT
        '博報堂の第1四半期実績報告: 仕入高合計は350億円、媒体収益は120億円、' ||
        'FC営業収入は80億円。予算達成率は全体で102%。' ||
        '特に好調だったのは食品業種で仕入高50億円、次いで自動車業種が45億円。' ||
        '一方で金融業種は予算未達の85%となった。' AS report_text
)
SELECT
    SNOWFLAKE.CORTEX.EXTRACT_ANSWER(report_text, '仕入高合計はいくらですか？') AS "Q1_仕入高",
    SNOWFLAKE.CORTEX.EXTRACT_ANSWER(report_text, '予算達成率は何%ですか？') AS "Q2_達成率",
    SNOWFLAKE.CORTEX.EXTRACT_ANSWER(report_text, '最も好調だった業種は？') AS "Q3_好調業種",
    SNOWFLAKE.CORTEX.EXTRACT_ANSWER(report_text, '予算未達の業種は？') AS "Q4_未達業種"
FROM report;

-- ============================================================================
-- 6. 実践的な活用パターン: AI Function をパイプラインに組み込む
-- ============================================================================
-- AI Function は Dynamic Table と組み合わせることで、
-- データ更新時に自動でAI分析結果を生成するパイプラインを構築できます。

-- --------------------------------------------------------------------------
-- 例6: AI分析付き月次レポート Dynamic Table
-- --------------------------------------------------------------------------

CREATE OR REPLACE DYNAMIC TABLE DT_MONTHLY_AI_REPORT
    TARGET_LAG = '2 MINUTES'
    WAREHOUSE = HAKUHODO_HANDSON_WH
    AS
    SELECT
        "年月",
        SUM("仕入高合計") AS "仕入高合計",
        SUM("媒体収益合計") AS "媒体収益合計",
        SUM("媒体収益予算合計") AS "媒体収益予算合計",
        CASE WHEN SUM("媒体収益予算合計") = 0 THEN NULL
             ELSE ROUND(SUM("媒体収益合計") * 100.0 / SUM("媒体収益予算合計"), 1)
        END AS "予実達成率",
        SUM("取引件数") AS "取引件数合計",
        SNOWFLAKE.CORTEX.COMPLETE(
            'claude-4-sonnet',
            '以下の月次仕入データの要点を50文字以内で日本語で述べてください。' ||
            '仕入高: ' || SUM("仕入高合計")::VARCHAR || '円, ' ||
            '媒体収益: ' || SUM("媒体収益合計")::VARCHAR || '円, ' ||
            '予算: ' || SUM("媒体収益予算合計")::VARCHAR || '円, ' ||
            '取引件数: ' || SUM("取引件数")::VARCHAR
        ) AS "AI月次サマリ",
        SNOWFLAKE.CORTEX.TRANSLATE(
            SNOWFLAKE.CORTEX.COMPLETE(
                'claude-4-sonnet',
                '以下の月次仕入データの要点を50文字以内で日本語で述べてください。' ||
                '仕入高: ' || SUM("仕入高合計")::VARCHAR || '円, ' ||
                '媒体収益: ' || SUM("媒体収益合計")::VARCHAR || '円'
            ),
            'ja', 'en'
        ) AS "AI_Monthly_Summary_EN"
    FROM DT_PURCHASE_MONTHLY_SUMMARY
    GROUP BY "年月";

-- データを確認
SELECT * FROM DT_MONTHLY_AI_REPORT
ORDER BY "年月" DESC
LIMIT 10;

